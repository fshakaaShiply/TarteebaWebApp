#!/usr/bin/env node
// Generates src/theme/tokens.css (Tailwind v4 @theme) and src/theme/tokens.ts from the
// design-system tokens.json (spec §27, packages/tokens replacement under decision R-01).
// Usage: pnpm sync:design [path/to/tokens.json]
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";

const source = resolve(
  process.argv[2] ??
    process.env.TARTEEBA_DESIGN_TOKENS ??
    "/mnt/c/Users/firas/workspace/Tarteebah/docs/design/tokens.json",
);
const t = JSON.parse(readFileSync(source, "utf8"));
const out = resolve(import.meta.dirname, "../src/theme");
mkdirSync(out, { recursive: true });

const colors = Object.fromEntries(t.color.tokens.map((c) => [c.name, c.value]));
const spacing = Object.fromEntries(t.spacing.tokens.map((s) => [s.name.replace("space-", ""), s.value]));
const radius = Object.fromEntries(t.radius.tokens.map((r) => [r.name.replace("radius-", ""), r.value]));
const shadow = Object.fromEntries(t.shadow.tokens.map((s) => [s.name.replace("shadow-", ""), s.value]));
const fonts = t.type.families;
const typeStyles = Object.fromEntries(
  t.type.groups.flatMap((g) =>
    g.styles.map((s) => [s.name, { family: g.family, size: s.fontSize, lineHeight: s.lineHeight, weight: s.fontWeight }]),
  ),
);

const header = `/* Generated by scripts/sync-design.mjs from tokens.json v${t.version}. Do not edit by hand. */\n`;

const css = [
  header,
  "@theme {",
  ...Object.entries(colors).map(([k, v]) => `  --color-${k}: ${v};`),
  `  --font-arabic: ${fonts.arabic};`,
  `  --font-latin: ${fonts.latin};`,
  ...Object.entries(radius).map(([k, v]) => `  --radius-${k}: ${v};`),
  ...Object.entries(shadow).map(([k, v]) => `  --shadow-${k}: ${v};`),
  "}",
  "",
  ...Object.entries(typeStyles).map(
    ([k, s]) =>
      `@utility text-${k} {\n  font-family: var(--font-${s.family});\n  font-size: ${s.size};\n  line-height: ${s.lineHeight};\n  font-weight: ${s.weight};\n}`,
  ),
  "",
].join("\n");

const ts = `${header}
export const colors = ${JSON.stringify(colors, null, 2)} as const;

export const spacing = ${JSON.stringify(spacing, null, 2)} as const;

export const radius = ${JSON.stringify(radius, null, 2)} as const;

export const shadow = ${JSON.stringify(shadow, null, 2)} as const;

export const fonts = ${JSON.stringify(fonts, null, 2)} as const;

export const typeStyles = ${JSON.stringify(typeStyles, null, 2)} as const;

export type ColorToken = keyof typeof colors;
`;

writeFileSync(resolve(out, "tokens.css"), css);
writeFileSync(resolve(out, "tokens.ts"), ts);
console.log(`tokens: ${Object.keys(colors).length} colours, ${Object.keys(typeStyles).length} type styles -> ${dirname(resolve(out, "tokens.ts"))}`);
